// Builds src/model/campusWalkTable.ts from the campus map's own walking graph
// (public/map/data.json), using the same edge lengths, path-type factors and
// entrance offsets as the map page's dijkstra. Run: node scripts/build-walk-table.mjs
// The paths come from OpenStreetMap and are not checked on foot, so every use of
// this table is labelled an estimate.
import { readFileSync, writeFileSync } from 'node:fs'

const D = JSON.parse(readFileSync(new URL('../public/map/data.json', import.meta.url), 'utf8'))
const FACT = [1, 1.04, 1.1, 1.25, 1] // same factors as the map page
const NN = D.gn.length / 2, NE = D.ge.length / 3
const adj = Array.from({ length: NN }, () => [])
for (let e = 0; e < NE; e++) {
  const a = D.ge[3 * e], b = D.ge[3 * e + 1]
  const len = Math.hypot(D.gn[2 * a] - D.gn[2 * b], D.gn[2 * a + 1] - D.gn[2 * b + 1]) / 10 * FACT[D.ge[3 * e + 2]]
  adj[a].push([b, len]); adj[b].push([a, len])
}
function dijkstra(place) {
  const dist = new Float64Array(NN).fill(1e9)
  const heap = []
  const push = (d, n) => { heap.push([d, n]); heap.sort((x, y) => x[0] - y[0]) }
  for (const [n, g] of place.acc) { const d = g / 10; if (d < dist[n]) { dist[n] = d; push(d, n) } }
  while (heap.length) {
    const [d, n] = heap.shift()
    if (d > dist[n]) continue
    for (const [m, len] of adj[n]) { const nd = d + len; if (nd < dist[m]) { dist[m] = nd; push(nd, m) } }
  }
  return dist
}
const places = D.places.filter(p => Array.isArray(p.acc) && p.acc.length)
const n = places.length
const metres = []
for (let i = 0; i < n; i++) {
  const dist = dijkstra(places[i])
  for (let j = 0; j < n; j++) {
    if (i === j) { metres.push(0); continue }
    let best = 1e9
    for (const [node, g] of places[j].acc) best = Math.min(best, dist[node] + g / 10)
    metres.push(best >= 1e8 ? -1 : Math.round(best))
  }
}
const rows = places.map(p => ({
  label: p.label, name: p.name,
  keys: [...new Set([p.label, p.name, ...(p.alias ?? []).filter(a => a.length >= 4), ...(p.inside ?? [])])],
}))
const out = `// GENERATED by scripts/build-walk-table.mjs from public/map/data.json. Do not edit by hand.
// Walking metres between campus places on the map's path graph (OpenStreetMap paths,
// not checked on foot). -1 means no path was found. Use only as a labelled estimate.
export const WALK_PLACES: readonly { label: string; name: string; keys: readonly string[] }[] = ${JSON.stringify(rows)}
export const WALK_METRES: readonly number[] = ${JSON.stringify(metres)}
`
writeFileSync(new URL('../src/model/campusWalkTable.ts', import.meta.url), out)
console.log(`${n} places, ${metres.length} pairs, ${(out.length / 1024).toFixed(1)} KB`)
